"""The agent loop. The LLM (Gemini) decides which tool to call next; code enforces the rules:

  - total tool calls <= MAX_TOOL_CALLS (then only final_answer is allowed)
  - failed run_query retries <= MAX_QUERY_RETRIES (enforced in the tool)
  - final_answer is refused until a cross-check has been done (if anything was calculated)
  - every figure in the written answer must match a tool result (number check, rewrite <= 2 times)
  - confidence is computed by code (confidence.py); sources and trace are generated by code

The LLM only does three things: plan, judge "is the evidence enough?", write the answer.
"""

