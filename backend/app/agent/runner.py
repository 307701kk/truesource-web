def _tools() -> list[types.Tool]:
    return [
        types.Tool(
            function_declarations=[
                types.FunctionDeclaration(name=n, description=d, parameters_json_schema=p)
                for n, d, p in TOOL_DECLS
            ]
        )
    ]


@dataclass
class Session:
    id: str
    user: dict
    history: list[types.Content] = field(default_factory=list)  # compact: questions + final answers
    masker: Masker | None = None


class Agent:
    def __init__(self, service, gateway: Gateway | None = None) -> None:
        self.service = service
        self.gateway = gateway or Gateway(AuditLog())
        self.sessions: dict[str, Session] = {}
        self._lock = threading.Lock()
        self._masker_for: tuple[int, Masker] | None = None

    # ------------------------------------------------------------------ public
    def ask(
        self,
        question: str,
        user: dict,
        session_id: str | None = None,
        glossary: list[dict] | None = None,
    ) -> dict:
        store = self.service.store
        if store is None:
            raise GatewayError("먼저 공유폴더를 분석하세요.")
        sess = self._session(session_id, user, store)
        ctx = QuestionCtx(question=question, indexed_at=self.service.status().get("finished_at"))
        tools = ToolBox(store, ctx, glossary)
        qid = uuid.uuid4().hex[:8]
        sess.user = user
        turn: list[types.Content] = [types.Content(role="user", parts=[types.Part(text=question)])]
        self._loop(sess, tools, ctx, turn, qid)
        resp = self._build_response(sess, ctx, tools, question, qid)
        self._remember(sess, question, resp)
        return resp

    # ------------------------------------------------------------------ internals
    def _session(self, sid: str | None, user: dict, store) -> Session:
        with self._lock:
            if self._masker_for is None or self._masker_for[0] != id(store):
                self._masker_for = (id(store), Masker(store))
            sess = self.sessions.get(sid or "")
            if sess is None:
                sess = Session(id=uuid.uuid4().hex[:12], user=user, masker=self._masker_for[1])
                self.sessions[sess.id] = sess
            sess.masker = self._masker_for[1]  # a re-scan gives a fresh mapping; conversations stay
            return sess

    def _cfg(self, tools: ToolBox, only_final: bool) -> types.GenerateContentConfig:
        latest = tools.latest_year()
        calling = types.FunctionCallingConfig(
            mode=types.FunctionCallingConfigMode.ANY,
            allowed_function_names=["final_answer"] if only_final else None,
        )
        return types.GenerateContentConfig(
            system_instruction=SYSTEM_PROMPT
            + f"\n\n[데이터 정보] 최신 연도: {latest}. 연도를 말하지 않으면 {latest}년입니다.",
            tools=_tools(),
            temperature=0.2,
            tool_config=types.ToolConfig(function_calling_config=calling),
            automatic_function_calling=types.AutomaticFunctionCallingConfig(disable=True),
        )

    def _loop(self, sess: Session, tools: ToolBox, ctx: QuestionCtx, turn: list, qid: str) -> None:
        nudges = 0
        for _ in range(config.MAX_TOOL_CALLS + config.MAX_NUDGES + config.MAX_NUMBER_RETRIES + 4):
            only_final = ctx.calls >= config.MAX_TOOL_CALLS
            reply = self.gateway.call_llm(
                purpose="plan_and_answer",
                contents=[*sess.history, *turn],
                gen_config=self._cfg(tools, only_final),
                user=sess.user,
                question_id=qid,
                masker=sess.masker,
            )
            turn.append(reply)
            calls = [p.function_call for p in reply.parts if p.function_call]
            if not calls:  # plain text instead of a tool call: push it back to the tool protocol
                nudges += 1
                if nudges > config.MAX_NUDGES:
                    ctx.final = {
                        "question_type": "질문형",
                        "answer": " ".join(p.text or "" for p in reply.parts).strip()
                        or "답변을 만들지 못했습니다.",
                        "_unstructured": True,
                    }
                    return
                turn.append(
                    types.Content(
                        role="user",
                        parts=[types.Part(text="도구를 호출하거나 final_answer 로 답하세요.")],
                    )
                )
                continue
            responses = []
            for fc in calls:
                result = self._dispatch(fc.name, dict(fc.args or {}), tools, ctx)
                result = json.loads(
                    json.dumps(result, ensure_ascii=False, default=str)
                )  # dates etc. -> str
                if fc.name != "final_answer" and "error" not in result:
                    ctx.tool_results.append(result)  # only real tool output may justify a figure
                responses.append(types.Part.from_function_response(name=fc.name, response=result))
            turn.append(types.Content(role="user", parts=responses))
            if ctx.ask or (ctx.final and not ctx.final.get("_rejected")):
                return
        if ctx.final is None or ctx.final.get("_rejected"):
            ctx.final = {
                "question_type": "질문형",
                "answer": "정해진 단계 안에 답을 완성하지 못했습니다.",
                "_unstructured": True,
            }

    def _dispatch(self, name: str, args: dict, tools: ToolBox, ctx: QuestionCtx) -> dict:
        if name == "final_answer":
            return self._final(args, tools, ctx)
        if name == "ask_user":
            return tools.execute(name, args)
        if ctx.calls >= config.MAX_TOOL_CALLS:
            return {
                "error": f"도구 호출 상한({config.MAX_TOOL_CALLS}회)에 도달했습니다. final_answer 로 답하세요."
            }
        ctx.calls += 1
        return tools.execute(name, args)

    def _final(self, args: dict, tools: ToolBox, ctx: QuestionCtx) -> dict:
        # rule 1: no calculated answer without a cross-check
        if ctx.queries and ctx.cross is None and ctx.calls < config.MAX_TOOL_CALLS:
            ctx.final = {"_rejected": True}
            return {
                "error": "교차검증 전에는 답할 수 없습니다. 다른 파일(다른 표)로 같은 지표를 run_query 한 뒤 cross_verify 하세요."
            }
        # rule 2: every figure must trace back to a tool result
        texts = [
            args.get("answer", ""),
            args.get("cause", ""),
            (args.get("claim") or {}).get("statement", ""),
            *(
                f"{c.get('rank_team', '')} {c.get('value', '')}"
                for c in args.get("comparison", []) or []
            ),
            *(
                f"{c.get('result', '')} {c.get('note', '')}"
                for c in (args.get("claim") or {}).get("checks", []) or []
            ),
        ]
        bad = numbers.check(texts, numbers.allowed_numbers(ctx.tool_results, ctx.question))
        if bad and ctx.number_retries < config.MAX_NUMBER_RETRIES:
            ctx.number_retries += 1
            ctx.final = {"_rejected": True}
            ctx.step(
                "final_answer",
                f"숫자 불일치({', '.join(bad)}) → 재작성 {ctx.number_retries}회",
                "warn",
            )
            return {
                "error": f"답변 속 숫자 {', '.join(bad)} 가 도구 결과에 없습니다. 도구가 준 값(display)만 그대로 인용해 다시 final_answer 하세요."
            }
        ctx.number_check = "failed" if bad else ("ok" if ctx.queries else "none")
        ctx.final = args
        ctx.step(
            "final_answer",
            "숫자 검증 통과" if not bad else f"숫자 검증 실패({', '.join(bad)})",
            "ok" if not bad else "warn",
        )
        return {"ok": True}

    # ------------------------------------------------------------------ response
    def _build_response(
        self, sess: Session, ctx: QuestionCtx, tools: ToolBox, question: str, qid: str
    ) -> dict:
        base = {
            "question": question,
            "session_id": sess.id,
            "question_id": qid,
            "tool_calls": ctx.calls,
            "trace": ctx.trace,
            "claim": None,
            "comparison_table": None,
            "cause": None,
            "sources": None,
            "search_results": None,
        }
        if ctx.ask:
            return base | {
                "type": "되묻기",
                "answer": ctx.ask["question"],
                "ask": ctx.ask,
                "confidence": None,
                "confidence_reason": None,
            }
        final = ctx.final or {}
        for t in {
            q["table"] for q in ctx.queries.values()
        }:  # data quality of everything that was used
            tools.note_quality(tools.quality_of(t))
        ctx.quality_notes[:] = list(dict.fromkeys(ctx.quality_notes))
        conf = confidence.evaluate(ctx)
        qtype = final.get("question_type", "질문형")
        if ctx.searched and not ctx.queries:
            qtype = "찾기형"
        elif final.get("claim"):
            qtype = "검증형"
        out = base | {
            "type": qtype,
            "answer": final.get("answer", ""),
            "confidence": conf["level"],
            "confidence_reason": conf["reason"],
            "confidence_signals": conf["signals"],
            "number_check": ctx.number_check,
        }
        if final.get("comparison"):
            out["comparison_table"] = final["comparison"]
        if final.get("cause"):
            out["cause"] = final["cause"]
        if final.get("claim"):
            out["claim"] = final["claim"]
        if ctx.sources:
            seen, srcs = set(), []
            for s in ctx.sources:
                key = (s["file"], s["sheet"], s["row"])
                if key not in seen:
                    seen.add(key)
                    srcs.append(s)
            out["sources"] = srcs
        if qtype == "찾기형" and ctx.search_hits:
            out["search_results"] = [
                {
                    "file": h["file"],
                    "location": f"{h['dept']} / {h['sheet']}",
                    "modified": f"{h['modified']} 수정",
                    "snippet": h["snippet"],
                    "relevance": "높음" if h["fresh"] == "ok" and h["exact"] else "보통",
                }
                for h in ctx.search_hits[:8]
            ]
        return out

    def _remember(self, sess: Session, question: str, resp: dict) -> None:
        """Keep a compact transcript so follow-ups ('그럼 2위는?') work without resending tool results."""
        if resp["type"] == "되묻기":
            summary = f"(되묻기) {resp['answer']}"
        else:
            summary = resp["answer"] + (f" [원인: {resp['cause']}]" if resp.get("cause") else "")
        sess.history += [
            types.Content(role="user", parts=[types.Part(text=question)]),
            types.Content(role="model", parts=[types.Part(text=summary)]),
        ]
        del sess.history[: -2 * config.MAX_HISTORY_TURNS]
